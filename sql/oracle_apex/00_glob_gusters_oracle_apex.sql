CREATE INDEX ix_director_nacionalidad ON director (nacionalidad_id);
CREATE INDEX ix_pelicula_nacionalidad ON pelicula (nacionalidad_id);
CREATE INDEX ix_pelicula_productora   ON pelicula (productora_id);
CREATE INDEX ix_pelicula_director     ON pelicula (director_id);
CREATE INDEX ix_actor_nacionalidad    ON actor (nacionalidad_id);
CREATE INDEX ix_reparto_actor         ON reparto (actor_id);
CREATE INDEX ix_cliente_aval          ON cliente (aval_cliente_id);
CREATE INDEX ix_ejemplar_estado       ON ejemplar (estado_id);
CREATE INDEX ix_renta_cliente         ON renta (cliente_id);
CREATE INDEX ix_ejemplar_renta_ejempl ON ejemplar_renta (ejemplar_id);

