-- =====================================================================================
-- TABLA: NACIONALIDAD
-- =====================================================================================
CREATE TABLE nacionalidad (
    nacionalidad_id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nombre          VARCHAR2(60) NOT NULL,
    CONSTRAINT pk_nacionalidad        PRIMARY KEY (nacionalidad_id),
    CONSTRAINT uq_nacionalidad_nombre UNIQUE (nombre)
);

-- =====================================================================================
-- TABLA: PRODUCTORA
-- =====================================================================================
CREATE TABLE productora (
    productora_id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nombre        VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_productora        PRIMARY KEY (productora_id),
    CONSTRAINT uq_productora_nombre UNIQUE (nombre)
);

-- =====================================================================================
-- TABLA: ESTADO (Ej.: Nuevo, Bueno, Regular, Dañado)
-- =====================================================================================
CREATE TABLE estado (
    estado_id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nombre    VARCHAR2(30) NOT NULL,
    CONSTRAINT pk_estado        PRIMARY KEY (estado_id),
    CONSTRAINT uq_estado_nombre UNIQUE (nombre)
);

-- =====================================================================================
-- TABLA: DIRECTOR
-- =====================================================================================
CREATE TABLE director (
    director_id     NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nombre          VARCHAR2(100) NOT NULL,
    nacionalidad_id NUMBER(10) NOT NULL,
    CONSTRAINT pk_director              PRIMARY KEY (director_id),
    CONSTRAINT fk_director_nacionalidad FOREIGN KEY (nacionalidad_id)
        REFERENCES nacionalidad (nacionalidad_id)
);

-- =====================================================================================
-- TABLA: PELICULA
-- =====================================================================================
CREATE TABLE pelicula (
    pelicula_id     NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    titulo          VARCHAR2(150) NOT NULL,
    anio            NUMBER(4) NOT NULL,
    nacionalidad_id NUMBER(10) NOT NULL,
    productora_id   NUMBER(10) NOT NULL,
    director_id     NUMBER(10) NOT NULL,
    CONSTRAINT pk_pelicula              PRIMARY KEY (pelicula_id),
    CONSTRAINT uq_pelicula_titulo_anio  UNIQUE (titulo, anio),
    CONSTRAINT chk_pelicula_anio        CHECK (anio BETWEEN 1888 AND 2100),
    CONSTRAINT fk_pelicula_nacionalidad FOREIGN KEY (nacionalidad_id)
        REFERENCES nacionalidad (nacionalidad_id),
    CONSTRAINT fk_pelicula_productora   FOREIGN KEY (productora_id)
        REFERENCES productora (productora_id),
    CONSTRAINT fk_pelicula_director     FOREIGN KEY (director_id)
        REFERENCES director (director_id)
);

-- =====================================================================================
-- TABLA: ACTOR
-- =====================================================================================
CREATE TABLE actor (
    actor_id        NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nombre          VARCHAR2(100) NOT NULL,
    nacionalidad_id NUMBER(10) NOT NULL,
    sexo            VARCHAR2(1) NOT NULL,
    CONSTRAINT pk_actor              PRIMARY KEY (actor_id),
    CONSTRAINT chk_actor_sexo        CHECK (sexo IN ('M', 'F')),
    CONSTRAINT fk_actor_nacionalidad FOREIGN KEY (nacionalidad_id)
        REFERENCES nacionalidad (nacionalidad_id)
);

-- =====================================================================================
-- TABLA: REPARTO (resuelve la relación N-M entre PELICULA y ACTOR)
-- =====================================================================================
CREATE TABLE reparto (
    reparto_id  NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    pelicula_id NUMBER(10) NOT NULL,
    actor_id    NUMBER(10) NOT NULL,
    rol         VARCHAR2(10) NOT NULL,
    CONSTRAINT pk_reparto                PRIMARY KEY (reparto_id),
    CONSTRAINT uq_reparto_pelicula_actor UNIQUE (pelicula_id, actor_id),
    CONSTRAINT chk_reparto_rol           CHECK (rol IN ('Principal', 'Secundario')),
    CONSTRAINT fk_reparto_pelicula       FOREIGN KEY (pelicula_id)
        REFERENCES pelicula (pelicula_id) ON DELETE CASCADE,
    CONSTRAINT fk_reparto_actor          FOREIGN KEY (actor_id)
        REFERENCES actor (actor_id) ON DELETE CASCADE
);

-- =====================================================================================
-- TABLA: CLIENTE
-- El aval es una autorreferencia opcional. La regla "un cliente no puede avalarse a
-- sí mismo" se aplica mediante la restricción CHECK chk_cliente_aval.
-- =====================================================================================
CREATE TABLE cliente (
    cliente_id      NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    dni             VARCHAR2(15) NOT NULL,
    nombre          VARCHAR2(100) NOT NULL,
    direccion       VARCHAR2(150) NOT NULL,
    telefono        VARCHAR2(20) NOT NULL,
    aval_cliente_id NUMBER(10),
    CONSTRAINT pk_cliente       PRIMARY KEY (cliente_id),
    CONSTRAINT uq_cliente_dni   UNIQUE (dni),
    CONSTRAINT chk_cliente_aval CHECK (aval_cliente_id IS NULL OR aval_cliente_id <> cliente_id),
    CONSTRAINT fk_cliente_aval  FOREIGN KEY (aval_cliente_id)
        REFERENCES cliente (cliente_id)
);

-- =====================================================================================
-- TABLA: EJEMPLAR
-- =====================================================================================
CREATE TABLE ejemplar (
    ejemplar_id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    numero      NUMBER(10) NOT NULL,
    pelicula_id NUMBER(10) NOT NULL,
    estado_id   NUMBER(10) NOT NULL,
    CONSTRAINT pk_ejemplar                PRIMARY KEY (ejemplar_id),
    CONSTRAINT uq_ejemplar_pelicula_numero UNIQUE (pelicula_id, numero),
    CONSTRAINT chk_ejemplar_numero        CHECK (numero >= 0),
    CONSTRAINT fk_ejemplar_pelicula       FOREIGN KEY (pelicula_id)
        REFERENCES pelicula (pelicula_id) ON DELETE CASCADE,
    CONSTRAINT fk_ejemplar_estado         FOREIGN KEY (estado_id)
        REFERENCES estado (estado_id)
);

-- =====================================================================================
-- TABLA: RENTA
-- =====================================================================================
CREATE TABLE renta (
    renta_id   NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    cliente_id NUMBER(10) NOT NULL,
    inicia     DATE NOT NULL,
    termina    DATE,
    CONSTRAINT pk_renta         PRIMARY KEY (renta_id),
    CONSTRAINT chk_renta_fechas CHECK (termina IS NULL OR termina >= inicia),
    CONSTRAINT fk_renta_cliente FOREIGN KEY (cliente_id)
        REFERENCES cliente (cliente_id)
);

-- =====================================================================================
-- TABLA: EJEMPLAR_RENTA (resuelve la relación N-M entre RENTA y EJEMPLAR)
-- =====================================================================================
CREATE TABLE ejemplar_renta (
    ejemplar_renta_id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    renta_id          NUMBER(10) NOT NULL,
    ejemplar_id       NUMBER(10) NOT NULL,
    entrega           DATE,
    CONSTRAINT pk_ejemplar_renta        PRIMARY KEY (ejemplar_renta_id),
    CONSTRAINT uq_ejemplar_renta_re_ej  UNIQUE (renta_id, ejemplar_id),
    CONSTRAINT fk_ejemplar_renta_renta  FOREIGN KEY (renta_id)
        REFERENCES renta (renta_id) ON DELETE CASCADE,
    CONSTRAINT fk_ejemplar_renta_ejempl FOREIGN KEY (ejemplar_id)
        REFERENCES ejemplar (ejemplar_id)
);

-- =====================================================================================
-- ÍNDICES SOBRE LLAVES FORÁNEAS (Oracle no los crea automáticamente)
