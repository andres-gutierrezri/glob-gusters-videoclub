-- EJECUCIÓN SEGURA / IDEMPOTENCIA:
--   Oracle (anterior a 23ai) no admite IF [NOT] EXISTS en estas sentencias. Por eso
--   cada una se ejecuta dentro de un bloque PL/SQL que primero consulta el diccionario
--   de datos (USER_TABLES, USER_TAB_COLUMNS, USER_INDEXES). Si el objeto ya existe (o
--   ya no existe, en el caso del DROP), la sentencia se omite sin error.
-- =====================================================================================

-- ---------------------------------------------------------------------------------
-- CREATE: crea una tabla de prueba para demostrar CREATE TABLE.
-- ---------------------------------------------------------------------------------
DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe FROM user_tables WHERE table_name = 'TABLA_PRUEBA';
    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE tabla_prueba (
                tabla_prueba_id NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
                descripcion     VARCHAR2(100) NOT NULL,
                CONSTRAINT pk_tabla_prueba PRIMARY KEY (tabla_prueba_id)
            )';
    END IF;
END;
/

COMMENT ON TABLE tabla_prueba IS 'Tabla temporal usada únicamente para demostrar sentencias DDL.';

-- ---------------------------------------------------------------------------------
-- ALTER: agrega la columna EMAIL a CLIENTE (correo electrónico opcional del socio).
-- ---------------------------------------------------------------------------------
DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe
      FROM user_tab_columns
     WHERE table_name = 'CLIENTE' AND column_name = 'EMAIL';
    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE cliente ADD (email VARCHAR2(120))';
    END IF;
END;
/

COMMENT ON COLUMN cliente.email IS 'Correo electrónico de contacto del socio (opcional).';

-- ---------------------------------------------------------------------------------
-- ALTER: agrega la columna DURACION_MINUTOS a PELICULA.
-- ---------------------------------------------------------------------------------
DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe
      FROM user_tab_columns
     WHERE table_name = 'PELICULA' AND column_name = 'DURACION_MINUTOS';
    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE pelicula ADD (duracion_minutos NUMBER(5))';
    END IF;
END;
/

COMMENT ON COLUMN pelicula.duracion_minutos IS 'Duración de la película en minutos.';

-- ---------------------------------------------------------------------------------
-- ALTER: amplía TELEFONO de CLIENTE a 25 caracteres (indicativo internacional).
-- No se repite NOT NULL: la columna ya lo tiene y Oracle lanzaría ORA-01442.
-- Repetir esta sentencia es seguro (el tamaño ya es 25).
-- ---------------------------------------------------------------------------------
ALTER TABLE cliente MODIFY (telefono VARCHAR2(25));

COMMENT ON COLUMN cliente.telefono IS 'Teléfono de contacto del socio, incluye indicativo internacional.';

-- ---------------------------------------------------------------------------------
-- CREATE INDEX: acelera las búsquedas de películas por título.
-- ---------------------------------------------------------------------------------
DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe FROM user_indexes WHERE index_name = 'IDX_PELICULA_TITULO';
    IF v_existe = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX idx_pelicula_titulo ON pelicula (titulo)';
    END IF;
END;
/

-- ---------------------------------------------------------------------------------
-- DROP: elimina la tabla de prueba creada al inicio del script.
-- ---------------------------------------------------------------------------------
DECLARE
    v_existe NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_existe FROM user_tables WHERE table_name = 'TABLA_PRUEBA';
    IF v_existe > 0 THEN
        EXECUTE IMMEDIATE 'DROP TABLE tabla_prueba PURGE';
    END IF;
END;
/
